"""The agent skills: hand-written guidance with resource notes generated from the catalog.

Each domain owns one skill file (`core` is `quarry`, the rest `quarry-<domain>`). The notes sit
between two markers and cover the domain's own resources, not its includes, so loading a domain
skill with `quarry` never repeats a note."""
from __future__ import annotations

from pathlib import Path

from quarry.catalog import Catalog, Resource, Route
from quarry.errors import QuarryError

SKILLS_ROOT = Path(__file__).resolve().parents[2] / "skills"
START = "<!-- quarry:resources start — generated by quarry skills build; edit the catalog -->"
END = "<!-- quarry:resources end -->"


def skill_path(root: Path, domain_id: str) -> Path:
    return root / ("quarry" if domain_id == "core" else f"quarry-{domain_id}") / "SKILL.md"


def _sentence(text: str) -> str:
    return text.strip().rstrip(".")


def _route(route: Route) -> str:
    parts = [f"every {route.min_interval:g} s"]
    if route.keyed_min_interval is not None:
        parts[0] += f" ({route.keyed_min_interval:g} s with a key)"
    if route.key_env:
        parts.append(f"key {route.key_env} ({route.auth})")
    if route.page_cap is not None:
        parts.append(f"page cap {route.page_cap}")
    parts.append("reports a total" if route.reports_total else "no total")
    return f"- {route.kind} `{route.url}`: " + "; ".join(parts)


def _resource(resource: Resource) -> str:
    owned = ", ".join(f"`{p}`" for p in resource.owned_prefixes()) or "none"
    lines = [f"### {resource.name} (`{resource.id}`)", "",
             f"Roles: {', '.join(resource.roles)}. Prefixes: {owned}.", ""]
    lines += [_route(r) for r in resource.routes]
    if resource.pitfalls:
        lines.append("")
        lines += [f"- {_sentence(p.summary)}. Handling: {_sentence(p.handling)}." for p in resource.pitfalls]
    return "\n".join(lines)


def render_notes(catalog: Catalog, domain_id: str) -> str:
    domain = catalog.domains[domain_id]
    return "\n\n".join(_resource(catalog.resources[rid]) for rid in domain.resources)


def _region(path: Path, text: str) -> tuple[int, int]:
    if text.count(START) != 1 or text.count(END) != 1 or text.index(START) > text.index(END):
        raise QuarryError("skill_unmarked", f"{path} needs exactly one start marker followed by one end marker")
    return text.index(START) + len(START), text.index(END)


def build(catalog: Catalog, root: Path, *, write: bool = True) -> tuple[list[Path], list[Path]]:
    """Regenerate each domain's notes. Returns (changed, unchanged); nothing is written unless
    every skill file is found and marked."""
    if not root.is_dir():
        raise QuarryError("no_checkout", f"{root} is not a directory: skills build runs in a quarry checkout")
    updates: dict[Path, tuple[str, str]] = {}
    for domain_id in sorted(catalog.domains):
        path = skill_path(root, domain_id)
        if not path.is_file():
            raise QuarryError("skill_missing", f"the {domain_id} domain has no skill file at {path}")
        text = path.read_text()
        start, end = _region(path, text)
        notes = render_notes(catalog, domain_id)
        updates[path] = (text, text[:start] + "\n" + (notes + "\n" if notes else "") + text[end:])
    changed = [p for p, (old, new) in updates.items() if old != new]
    if write:
        for path in changed:
            path.write_text(updates[path][1])
    return changed, [p for p in updates if p not in changed]
